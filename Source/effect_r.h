#pragma once
#pragma once
#include <DxLib.h>
#include <vector>

//====================================================
// EffectR クラス
// Rキー用の雷柱エフェクト
// ・プレイヤー周囲に発生する青い雷柱
// ・直線的だけどジッターで微妙にブレる
// ・画面フラッシュも同時に発生
//====================================================
class EffectR
{
public:
    EffectR(float X,float Y,float Z);  // コンストラクタ
    ~EffectR() = default; // デストラクタ

    //================================================
    // 初期化：必要ならテクスチャや設定読み込み
    //================================================
    bool Load();

    //================================================
    // 発動：雷を出現させる
    //================================================
    void Trigger(const VECTOR& pos);

    //================================================
    // 更新：毎フレーム呼ぶ
    //================================================
    void UpdateFollow(const VECTOR& playerPos);

    //================================================
    // 描画：雷柱＋ジッター＋画面フラッシュ
    //================================================
    void Draw() const;

private:
    //================================================
    // Clamp01: 0.0～1.0に制限
    //================================================
    static float Clamp01(float v)
    {
        if (v < 0.0f) return 0.0f;
        if (v > 1.0f) return 1.0f;
        return v;
    }

    //================================================
    // 雷1本の情報
    //================================================
    struct Bolt
    {
        VECTOR base;     // 雷の基準位置（地面の座標など）
        float  life;     // 残り寿命
        float  maxLife;  // 最大寿命

        float  height;   // 雷の高さ
        int    segs;     // 分割数（直線を何個に分けるか）

        float  jitter;   // どれくらいブレるか
        float  jitterHz; // ジッターの変化スピード
        float  timeAcc;  // 時間積算（ジッター計算用）

        std::vector<VECTOR> points; // 実際に描画する頂点列

        float flash;     // 画面フラッシュ用の強さ
    };


    std::vector<Bolt> mBolts; // 登録されている雷柱リスト

    //================================================
    // 見た目パラメータ
    //================================================
    float mDefaultLife = 3.0f;   // 雷1本の寿命（秒）
    float mHeight = rand() % 1000 + 1000;      // 雷の高さ
    int   mSegments = 16;         // 雷を何分割するか
    float mJitter = 42.0f;        // ブレ幅
    float mJitterHz = 55.0f;      // ブレ変化速度
    float mYOffset = 5.0f;        // 地面からの微調整

    int mGlowThickness = 10;       // 外側の光（グロー）太さ
    int mCoreThickness = 3;       // 中心の雷太さ

    // 青い雷の色
    int mColorR = 80;
    int mColorG = 160;
    int mColorB = 255;

    int mGlowAdd = 255;           // グローの加算輝度
    int mCoreAdd = 255;           // コアの加算輝度

    float mScreenFlashStrength = 0.35f; // フラッシュの強さ（0.0～1.0）

    VECTOR mvPosition;

    //================================================
    // 雷の頂点列を計算する（ジッターを含む）
    //================================================
    void RebuildBoltPoints(Bolt& b);
};
