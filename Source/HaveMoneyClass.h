#pragma once
#include"dxlib.h"
#include"Object2D.h"
#include"Object3D.h"

// プレイヤーの所持金（通貨・スコア）をカプセル化し、不正な値の混入や増減時のUI演出を一元管理するクラス
class HaveMoneyClass
{
public:
    // 入力: money (初期所持金) / 出力: なし
    // 副作用: 所持金管理クラスを初期化し、初期値のセットアップを行う
    HaveMoneyClass(int money);

    // 入力: なし / 出力: なし
    // 副作用: なし（動的確保したリソースが追加された際、メモリリークを防ぐために明示的に破棄する）
    ~HaveMoneyClass();

    // 入力: なし / 出力: なし
    // 副作用: 所持金が増減した際の、数字がパラパラと切り替わるようなUIのカウントアニメーションを進行させる
    void Update();

    // 入力: なし / 出力: なし
    // 副作用: 現在の所持金（またはアニメーション中の数値）をスクリーン座標上にUIとしてバッファへ登録する
    void Draw();

    // 入力: money (獲得額) / 出力: なし
    // 副作用: 敵撃破時などに呼び出し、値のオーバーフロー（カンスト超えによる負数化バグ）をガードしつつ加算する
    void AddMoney(int money);

    // 入力: money (消費額) / 出力: なし
    // 副作用: ショップ購入時などに呼び出し、値のアンダーフロー（所持金がマイナスになるバグ）を防ぎつつ減算する
    void PullMoney(int money);

    // 入力: なし / 出力: 現在の所持金(int) / 副作用: なし
    // ショップでのアイテム購入時など、要求コストに対する支払い能力（残高）があるかの判定判定に使用する
    int HaveMoney() { return money_; }

private:
    int money_;          // 意図せぬ外部からの直接書き換えや不正計算を防ぐため、カプセル化された実際の所持金額
    Object3D* parent_;   // 3D空間上で財布の持ち主（プレイヤー等）の頭上にUIを追従させるための親オブジェクト参照
};