float Player3D::GetAllStatusState(Object3D::StatusState state)
{
	if (mpLevelUp == nullptr || mpBuffManager == nullptr)return 0;

	if (state == Status_Attack)
	{
		return mfNormalAttack + mpBuffManager->GetBuff(state)+mpLevelUp->GetAttack() + mfUpgradeAttack;
	}
	if (state == Status_Speed)
	{
		return speed_ + mpBuffManager->GetBuff(state)+mpLevelUp->GetSpeed() + mfUpgradeSpeed;
	}
	if (state == Status_Hp)
	{
		return max_hp_ + mpLevelUp->GetHp() + mfUpgradeMaxHp;
	}


}

