#pragma once
#include <DxLib.h>
#include <vector>

//====================================================
// EffectU クラス
// Uキー用：魔法陣演出 (Effekseer)
//====================================================
class EffectU
{
public:
    EffectU() = default;
    ~EffectU();

    //====================================================
    // エフェクトの読み込み
    //====================================================
    bool Load();

    //====================================================
    // Uキー押した瞬間：魔法陣を出す
    //====================================================
    void StartHold(const VECTOR& playerPos);

    //====================================================
    // Uキー離した瞬間：魔法陣を消す（砕く）
    //====================================================
    void ReleaseAndShatter();

    //====================================================
    // 毎フレーム呼ぶ
    // - 中心位置追従
    //====================================================
    void UpdateFollow(const VECTOR& playerPos);

    //====================================================
    // 描画 (EffekseerManagerが描画するので空でOK)
    //====================================================
    void Draw() const;

private:
    int playing_handle_ = -1; // Effekseer再生ハンドル
    bool is_holding_ = false;
    float y_offset_ = 2.0f;
};